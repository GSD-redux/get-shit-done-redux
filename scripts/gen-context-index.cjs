#!/usr/bin/env node
'use strict';

/**
 * gen-context-index.cjs — generates gsd-core/bin/lib/context-index.cjs from
 * the predicate declarations (`` `CLASS.subkey=value` `` lines) in the
 * repo-root CONTEXT.md.
 *
 * Usage:
 *   node scripts/gen-context-index.cjs              # print to stdout
 *   node scripts/gen-context-index.cjs --write      # write context-index.cjs
 *   node scripts/gen-context-index.cjs --check      # exit 1 if committed file is stale
 *
 * ADR-1671 ("Dynamic context management platform", #2928) Phase 1 commit 1.
 * Depends on the COMPILED gsd-core/bin/lib/context-predicates.cjs
 * (src/context-predicates.cts, built by `npm run build:lib`). This is safe
 * for CI: `.github/workflows/test.yml` runs `build:lib` before `lint:ci`.
 */

const fs = require('node:fs');
const path = require('node:path');

const { ExitError, runMain } = require('./lib/cli-exit.cjs');

const ROOT = path.resolve(__dirname, '..');
const CONTEXT_PREDICATES_LIB_PATH = path.join(ROOT, 'gsd-core', 'bin', 'lib', 'context-predicates.cjs');
const CONTEXT_PATH = path.join(ROOT, 'CONTEXT.md');
const INDEX_PATH = path.join(ROOT, 'gsd-core', 'bin', 'lib', 'context-index.cjs');

// ─── Loaders ──────────────────────────────────────────────────────────────────

/**
 * Load the compiled context-predicates library. The artifact is a gitignored
 * tsc build output of src/context-predicates.cts and only exists after
 * `npm run build:lib`. Throws a clean ExitError (never a bare
 * MODULE_NOT_FOUND stack) naming the remedy when it is missing.
 *
 * @returns {{ parsePredicates: Function, selectPredicates: Function, buildIndex: Function }}
 */
function loadContextPredicatesLib() {
  try {
    delete require.cache[require.resolve(CONTEXT_PREDICATES_LIB_PATH)];
    return require(CONTEXT_PREDICATES_LIB_PATH);
  } catch (err) {
    throw new ExitError(
      1,
      `Cannot load ${path.relative(ROOT, CONTEXT_PREDICATES_LIB_PATH)}: ${err && err.message}\n` +
      'Run:\n  npm run build:lib\n',
    );
  }
}

/**
 * Read the repo-root CONTEXT.md. Throws a clean ExitError naming the path
 * (never a bare stack trace) when it is missing or unreadable.
 *
 * @returns {string}
 */
function readContextMarkdown() {
  try {
    return fs.readFileSync(CONTEXT_PATH, 'utf8');
  } catch (err) {
    throw new ExitError(1, `Cannot read ${path.relative(ROOT, CONTEXT_PATH)}: ${err && err.message}`);
  }
}

/**
 * Build a fresh ContextIndex from the current CONTEXT.md content.
 *
 * @returns {object}
 */
function buildFreshIndex() {
  const { parsePredicates, buildIndex } = loadContextPredicatesLib();
  const markdown = readContextMarkdown();
  const { predicates } = parsePredicates(markdown);
  return buildIndex(predicates);
}

// ─── Serialization ────────────────────────────────────────────────────────────

/**
 * Serialize a ContextIndex to a committed CommonJS module string.
 *
 * @param {object} index
 * @returns {string}
 */
function serializeIndex(index) {
  const lines = [];

  lines.push("'use strict';");
  lines.push('');
  lines.push('/**');
  lines.push(' * context-index.cjs — generated by scripts/gen-context-index.cjs');
  lines.push(' * DO NOT EDIT BY HAND. Run: node scripts/gen-context-index.cjs --write');
  lines.push(' * ADR-1671 — Dynamic context management platform, predicate fact-store index.');
  lines.push(' * Deterministic index of every `CLASS.subkey=value` predicate declared in');
  lines.push(' * the repo-root CONTEXT.md. See src/context-predicates.cts.');
  lines.push(' */');
  lines.push('');
  lines.push('const CONTEXT_INDEX = ' + JSON.stringify(index, null, 2) + ';');
  lines.push('');
  lines.push('module.exports = { CONTEXT_INDEX };');
  lines.push('');

  return lines.join('\n');
}

/**
 * Normalize line endings to LF for CRLF-agnostic full-content comparison.
 *
 * @param {string} content
 * @returns {string}
 */
function normalizeLineEndings(content) {
  return content.replace(/\r/g, '');
}

/**
 * Extract the sorted list of duplicate predicate ids from a built index.
 *
 * @param {{ duplicates: Array<{ id: string, count: number }> }} index
 * @returns {string[]}
 */
function duplicateIds(index) {
  return index.duplicates.map((d) => d.id);
}

// ─── Main ─────────────────────────────────────────────────────────────────────

function main() {
  const flag = process.argv[2];

  if (flag === undefined) {
    process.stdout.write(serializeIndex(buildFreshIndex()) + '\n');
    return;
  }

  if (flag === '--check') {
    const live = buildFreshIndex();

    const dups = duplicateIds(live);
    if (dups.length > 0) {
      throw new ExitError(
        1,
        'CONTEXT.md has duplicate predicate id(s): ' + dups.join(', ') + '\n' +
        'Each predicate id must be declared exactly once.\n',
      );
    }

    if (!fs.existsSync(INDEX_PATH)) {
      throw new ExitError(
        1,
        `${path.relative(ROOT, INDEX_PATH)} does not exist. Run:\n  node scripts/gen-context-index.cjs --write\n`,
      );
    }

    let committedText;
    try {
      committedText = fs.readFileSync(INDEX_PATH, 'utf8');
      delete require.cache[require.resolve(INDEX_PATH)];
      const committedModule = require(INDEX_PATH);
      if (!committedModule || !committedModule.CONTEXT_INDEX) {
        throw new Error('module does not export CONTEXT_INDEX');
      }
    } catch (err) {
      throw new ExitError(
        1,
        `${path.relative(ROOT, INDEX_PATH)} is unparseable: ${err && err.message}\n` +
        'Run:\n  node scripts/gen-context-index.cjs --write\n',
      );
    }

    const liveText = serializeIndex(live);
    if (normalizeLineEndings(committedText) !== normalizeLineEndings(liveText)) {
      throw new ExitError(
        1,
        `${path.relative(ROOT, INDEX_PATH)} is stale. Run:\n  node scripts/gen-context-index.cjs --write\n`,
      );
    }

    process.stdout.write(`${path.relative(ROOT, INDEX_PATH)} is up to date.\n`);
    return;
  }

  if (flag === '--write') {
    const index = buildFreshIndex();
    fs.mkdirSync(path.dirname(INDEX_PATH), { recursive: true });
    fs.writeFileSync(INDEX_PATH, serializeIndex(index), 'utf8');
    const dupCount = index.duplicates.length;
    process.stdout.write(
      `Wrote ${path.relative(ROOT, INDEX_PATH)}\n` +
      `  ${index.count} predicates, ${Object.keys(index.classes).length} classes, ` +
      `${dupCount} duplicate id${dupCount !== 1 ? 's' : ''}\n`,
    );
    return;
  }

  process.stderr.write('Usage: gen-context-index.cjs [--write|--check]\n');
  throw new ExitError(1);
}

// ─── Exports (for tests) ──────────────────────────────────────────────────────

module.exports = {
  loadContextPredicatesLib,
  readContextMarkdown,
  buildFreshIndex,
  serializeIndex,
  normalizeLineEndings,
  duplicateIds,
  CONTEXT_PREDICATES_LIB_PATH,
  CONTEXT_PATH,
  INDEX_PATH,
};

// ─── CLI entry point ──────────────────────────────────────────────────────────

if (require.main === module) {
  runMain(main);
}
